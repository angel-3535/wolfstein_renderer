Color Get_Wall_Color(int wall_type, int side) {
  Color color;
  switch (wall_type) {
  case 1:
    color = (Color){255, 0, 0, 255};
    break;
  case 2:
    color = (Color){0, 255, 0, 255};
    break;
  case 3:
    color = (Color){0, 0, 255, 255};
    break;
  case 4:
    color = (Color){255, 255, 255, 255};
    break;
  default:
    color = (Color){255, 255, 0, 255};
    break;
  }
  if (side == 1) {
    color.r = color.r / 2;
    color.g = color.g / 2;
    color.b = color.b / 2;
  }

  return color;
}
